	# WE CAN USE PVD GET VDD VOLTAGE IS 3V3 OR 5V

	DEFW PVD_PLS_2V1, "PVD-PLS-2V1"
	LIT PVD_PLS_2V1
	ret
	ENDW PVD_PLS_2V1

	DEFW PVD_PLS_2V3, "PVD-PLS-2V3"
	LIT PVD_PLS_2V3
	ret
	ENDW PVD_PLS_2V3

	DEFW PVD_PLS_3V0, "PVD-PLS-3V0"
	LIT PVD_PLS_3V0
	ret
	ENDW PVD_PLS_3V0

	DEFW PVD_PLS_4V0, "PVD-PLS-4V0"
	LIT PVD_PLS_4V0
	ret
	ENDW PVD_PLS_4V0

	DEFW PVD_PLSSTORE, "PVD-PLS!"
	# ( PLS -- )
	mv x14, x15
	PPOP x15
	li x13, PWR_BASE
	lw x12, R32_PWR_CTLR(x13)
	li x11, ~(PVD_PLS_MASK)
	and x12, x12, x11
	li x11, PVD_PLS_MASK
	and x14, x14, x11
	or x12, x12, x14
	sw x12, R32_PWR_CTLR(x13)
	ret
	ENDW PVD_PLSSTORE

	DEFW PVD_OUTLOAD, "PVD-OUT@"
	# ( -- FLAG )
	PPUSH x15
	li x14, PWR_BASE
	lw x13, R32_PWR_CSR(x14)
	andi x13, x13, PVD0_BIT
	li x15, 0
	beqz x13, 1f
	li x15, -1
1:
	ret
	ENDW PVD_OUTLOAD

	DEFW VDD_IS5V, "VDD-5V?"
	# ( -- FLAG )
	RPUSH x1
	FC PVD_PLS_4V0, PVD_PLSSTORE
	FC 0X1, DELAY, PVD_OUTLOAD
	RPOP x1
	TC INVERT
	ENDW PVD_IS5V
