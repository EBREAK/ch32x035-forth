	DEFW TICKSLOAD, "TICKS@"
	# ( -- TICKS_LO TICKS_HI )
	la x14, SYSTICK_BASE
	lw x13, R32_SYSTICK_CNTH(x14)
1:
	lw x12, R32_SYSTICK_CNTL(x14)
	lw x11, R32_SYSTICK_CNTH(x14)
	bne x11, x13, 2f
	addi x9, x9, -8
	sw x15, 4(x9)
	sw x12, 0(x9)
	mv x15, x13
	ret
2:
	mv x13, x11
	j 1b
	ENDW TICKSLOAD

	.SET TICKS_PER_US, 6
	.SET TICKS_PER_MS, 6000

	DEFW MICROS, "MICROS"
	# ( -- US_LO US_HI )
	RPUSH x1
	FC TICKSLOAD
	LIT TICKS_PER_US, 0
	RPOP x1
	TC UXDIVID
	ENDW MICROS

	DEFW MILLIS, "MILLIS"
	# ( -- MS_LO MS_HI )
	RPUSH x1
	FC TICKSLOAD
	LIT TICKS_PER_MS, 0
	RPOP x1
	TC UXDIVID
	ENDW MILLIS

	DEFW DELAY_US, "DELAY-US"
	# ( CNT -- )
	RPUSH x1
	addi x15, x15, 1
	FC 0X0, MICROS, XPLUS
1:
	FC PAUSE, 2DUP, MICROS, XMINUS
	FC OR, GTZ, INVERT
	ZBR 1b
	RPOP x1
	TC 2DROP
	ENDW DELAY_US

	DEFW DELAY_MS, "DELAY-MS"
	# ( CNT -- )
	RPUSH x1
	addi x15, x15, 1
	FC 0X0, MILLIS, XPLUS
1:
	FC PAUSE, 2DUP, MILLIS, XMINUS
	FC OR, GTZ, INVERT
	ZBR 1b
	RPOP x1
	TC 2DROP
	ENDW DELAY_MS
	
	DEFW SYSTICK_INIT, "SYSTICK-INIT"
	# ( -- )
	li x14, -1
	li x13, -1
	li x12, SYSTICK_BASE
	sw x0, R32_SYSTICK_SR(x12)
	sw x0, R32_SYSTICK_CNTL(x12)
	sw x0, R32_SYSTICK_CNTH(x12)
	sw x14, R32_SYSTICK_CMPL(x12)
	sw x13, R32_SYSTICK_CMPH(x12)
	fence iorw,iorw
	li x11, (SYSTICK_STRE | SYSTICK_STCLK_HCLK_DIV8 | SYSTICK_STE)
	sw x11, R32_SYSTICK_CTLR(x12)
	ret
	ENDW SYSTICK_INIT

	
