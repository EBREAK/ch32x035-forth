TEST_MEMCMP:
	LIT 0, 0, 0, 0
	FC MEMCMP, EQCHK
	.PUSHSECTION .rodata.testdata
TD_MEMCMP_0:
	.ASCII "HELLO WORLD"
TD_MEMCMP_1:
	.ASCII "HELLO FORTH"
TD_MEMCMP_2:
	.ASCII "HELLO MIKU."
	.POPSECTION
	LIT 0
	LAT TD_MEMCMP_0, TD_MEMCMP_1
	LIT 6
	FC MEMCMP, EQCHK
	LIT 1
	LAT TD_MEMCMP_0, TD_MEMCMP_1
	LIT 7
	FC MEMCMP, EQCHK
	LIT 1
	LAT TD_MEMCMP_0, TD_MEMCMP_1
	LIT 11
	FC MEMCMP, EQCHK
	LIT -1
	LAT TD_MEMCMP_1, TD_MEMCMP_0
	LIT 11
	FC MEMCMP, EQCHK
	LIT -1
	LAT TD_MEMCMP_1, TD_MEMCMP_2
	LIT 11
	FC MEMCMP, EQCHK
	LIT 1
	LAT TD_MEMCMP_2, TD_MEMCMP_1
	LIT 11
	FC MEMCMP, EQCHK, PZCHK

TEST_ISNUMBER:
	LIT 0, 0, 0
	FC ISNUMBER, EQCHK
	LIT 0, 0, 1
	FC ISNUMBER, EQCHK
	.PUSHSECTION .rodata.testdata
TD_ISNUMBER_0:
	.ASCII "(1234"
TD_ISNUMBER_1:
	.ASCII "$MASK"
TD_ISNUMBER_2:
	.ASCII "$G123456"
TD_ISNUMBER_3:
	.ASCII "$0123456789ABCDEF"
