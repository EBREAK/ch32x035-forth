	FC SWAP, ISNUMBER, EQCHK
	LIT 0, 5
	LAT TD_ISNUMBER_1
	FC SWAP, ISNUMBER, EQCHK
	LIT 0, 8
	LAT TD_ISNUMBER_2
	FC SWAP, ISNUMBER, EQCHK
	LIT -1, 17
	LAT TD_ISNUMBER_3
	FC SWAP, ISNUMBER, EQCHK
	FC PZCHK

