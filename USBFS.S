USBFSD_PROC_SETUP:
	li x13, USBFS_UEP_T_TOG | USBFS_UEP_T_RES_NAK | USBFS_UEP_R_TOG | USBFS_UEP_R_RES_NAK
	sh x13, R16_UEP0_CTRLH(x14)
	la x13, USBFSD_EP0_DMABUF
	la x12, USBFSD_SETUP_COPY
	lw x11, 4(x13)
	sw x11, 4(x12)
	lw x11, 0(x13)
	sw x11, 0(x12)
	mv x12, x11
	li x11, (USB_DESC_TYPE_DEV << 24) | (USB_GET_DESCRIPTOR << 8) | (USB_SETUP_REQDIR_IN | USB_SETUP_REQTYPE_STAND)
	beq x12, x11, USBFSD_PROC_SETUP_GET_DESC_DEV
	li x11, (USB_DESC_TYPE_CFG << 24) | (USB_GET_DESCRIPTOR << 8) | (USB_SETUP_REQDIR_IN | USB_SETUP_REQTYPE_STAND)
	beq x12, x11, USBFSD_PROC_SETUP_GET_DESC_CFG
	li x11, 0xFFFF
	and x12, x12, x11
	li x11, (USB_SET_ADDRESS << 8) | (USB_SETUP_REQDIR_OUT | USB_SETUP_REQTYPE_STAND)
	beq x12, x11, USBFSD_PROC_SETUP_SET_ADDR
	li x11, (USB_SET_CONFIGURATION << 8) | (USB_SETUP_REQDIR_OUT | USB_SETUP_REQTYPE_STAND)
	beq x12, x11, USBFSD_PROC_SETUP_SET_CFG
	li x11, (USB_SET_LINE_CODING << 8) | (USB_SETUP_REQDIR_OUT | USB_SETUP_REQTO_ITF | USB_SETUP_REQTYPE_CLASS)
	beq x12, x11, USBFSD_PROC_SETUP_SET_LINE_CODING
	li x11, (USB_GET_LINE_CODING << 8) | (USB_SETUP_REQDIR_IN | USB_SETUP_REQTO_ITF | USB_SETUP_REQTYPE_CLASS)
	beq x12, x11, USBFSD_PROC_SETUP_GET_LINE_CODING
	li x11, (USB_SET_CONTROL_LINE_STATE << 8) | (USB_SETUP_REQDIR_OUT | USB_SETUP_REQTO_ITF | USB_SETUP_REQTYPE_CLASS)
	beq x12, x11, USBFSD_PROC_SETUP_SET_CONTROL_LINE_STATE
	j USBFSD_EP0_STALL

