	FC USBFSD_HID0_OUT_FIFO, FIFO8_NUM_FREE
	LIT 32
	FC GT, USBFSD_EP4_OUT_IS_NAK, AND
	ZBR 1f
	li x14, USBFS_BASE
	lhu x13, R16_UEP4_CTRLH(x14)
