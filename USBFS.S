	lw x12, 0(x13)
	li x11, 0xFFFF
	and x12, x12, x11
	li x11, (USB_SET_ADDRESS << 8) | (USB_SETUP_REQDIR_OUT | USB_SETUP_REQTYPE_STAND)
	beq x12, x11, USBFSD_PROC_EP0_IN_SET_ADDR
	j USBFSD_PROC_TRANS_END

