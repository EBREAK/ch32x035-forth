	DEFW USBFSD_GPIO_INIT, "USBFSD-GPIO-INIT"
	# USB D+ PC 17
	# USB D- PC 16
	# ( -- )
	RPUSH x1
	FC VDD_IS5V
	li x14, AFIO_BASE
	lw x13, R32_AFIO_CTLR(x14)
	li x12, ~(AFIO_USBPHY_LDODIS | AFIO_USB_DP_PUE_MASK | AFIO_USB_DM_PUE_MASK)
	and x13, x13, x12
	bnez x15, 1f
	li x12, AFIO_USB_DP_PUE_2K # USB FULL SPEED, 1.5K PULL UP D+
1:
	beqz x15, 1f
	li x12, AFIO_USB_DP_PUE_10K # USB FULL SPEED, 10K PULL UP D+
1:
	or x13, x13, x12
	xori x12, x15, -1
	andi x12, x12, 0x1
	PPOP x15
	slli x12, x12, 6 # AFIO_USBPHY_LDODIS/EN
	or x13, x13, x12
	li x12, AFIO_USBPHY_IOEN
	or x13, x13, x12
	sw x13, R32_AFIO_CTLR(x14)

	li x14, GPIOC_BASE
	lw x13, R32_GPIO_CFGXR(x14)
	andi x13, x13, ~(0xFF)
	ori x13, x13, 0x44
	sw x13, R32_GPIO_CFGXR(x14)
	lw x13, R32_GPIO_OUTDR(x14)
	li x12, (1 << 17) # USB FULL SPEED PULL UP D+
	or x13, x13, x12
	sw x13, R32_GPIO_OUTDR(x14)
	lw x13, R32_GPIO_CFGXR(x14)
	andi x13, x13, ~(0xFF)
	ori x13, x13, 0x84
	sw x13, R32_GPIO_CFGXR(x14)
	RPOP x1
	ret
	ENDW USBFSD_GPIO_INIT

	DEFCONST USBFS_BASE, "USBFS-BASE", USBFS_BASE
	DEFCONST R8_USBFS_DEV_ADDR, "R8-USBFS-DEV-ADDR", R8_USBFS_DEV_ADDR

	DEFW USBFSD_INIT, "USBFSD-INIT"
	# ( -- )
	li x14, USBFS_BASE

	sb x0, R8_USBFS_BASE_CTRL(x14)
	sb x0, R8_UEP4_1_MOD(x14)
	sb x0, R8_UEP2_3_MOD(x14)
	sb x0, R8_UEP567_MOD(x14)
	sw x0, R32_UEPX_MOD(x14)

	la x13, FORTH_DP
	lw x12, 0(x13)
	addi x12, x12, 3
	andi x12, x12, -4
	sw x12, R32_UEP0_DMA(x14)
	# EP0 EP4 SHARE A DMA ADDRESS REGISTER
	addi x12, x12, (64 + 64 + 64) # EP0(OUT+IN) + EP4(OUT) + EP4(IN)
	sw x12, 0(x13)

	li x13, (USBFS_UEP4_TX_EN | USBFS_UEP4_RX_EN)
	sb x13, R8_UEP4_1_MOD(x14)

	sh x0, R16_UEP0_TX_LEN(x14)
	sh x0, R16_UEP4_TX_LEN(x14)

	li x13, USBFS_UEP_R_RES_ACK | USBFS_UEP_T_RES_NAK
	sh x13, R16_UEP0_CTRLH(x14)
	sh x13, R16_UEP4_CTRLH(x14)

	sb x0, R8_USBFS_DEV_ADDR(x14)
	li x13, USBFS_UC_DEV_PU_EN | USBFS_UC_INT_BUSY | USBFS_UC_DMA_EN
	sb x13, R8_USBFS_BASE_CTRL(x14)

	li x13, 0xFF
	sb x13, R8_USBFS_INT_FG(x14)

	li x13, USBFS_UD_PD_DIS | USBFS_UD_PORT_EN
	sb x13, R8_USBFS_UDEV_CTRL(x14)

	li x13, USBFS_UIE_BUS_RST | USBFS_UIE_TRANSFER | USBFS_UIE_SUSPEND
	sb x13, R8_USBFS_INT_EN(x14)

	ret
	ENDW USBFSD_INIT
