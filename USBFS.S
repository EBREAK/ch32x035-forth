	lhu x11, 4(x13)
	sh x11, 4(x12)
	lbu x11, 6(x13)
	sb x11, 6(x12)
	li x13, 0
	li x12, 0
	j USBFSD_EP0_UPLOAD

USBFSD_PROC_EP0_OUT:
	lbu x13, R8_USBFS_INT_ST(x14)
	andi x12, x13, USBFS_UIS_TOG_OK
	beqz x12, USBFSD_PROC_TRANS_END
	la x13, USBFSD_SETUP_COPY
	lw x12, 0(x13)
	li x11, 0xFFFF
	and x12, x12, x11
	li x11, (USB_SET_LINE_CODING << 8) | (USB_SETUP_REQDIR_OUT | USB_SETUP_REQTO_ITF | USB_SETUP_REQTYPE_CLASS)
	beq x12, x11, USBFSD_PROC_EP0_OUT_SET_LINE_CODING
	lhu x0, R16_USBFS_RX_LEN(x14)
	j USBFSD_PROC_TRANS_END

USBFSD_PROC_EP4_IN:
	lhu x13, R16_UEP4_CTRLH(x14)
	xori x13, x13, USBFS_UEP_T_TOG
	sh x13, R16_UEP4_CTRLH(x14)
	lhu x13, R16_UEP4_CTRLH(x14)
	andi x13, x13, ~(USBFS_UEP_T_RES_MASK)
	ori x13, x13, (USBFS_UEP_T_RES_NAK)
	sh x13, R16_UEP4_CTRLH(x14)
	j USBFSD_PROC_TRANS_END

USBFSD_EP4_OUT_STALL:
	# FATAL ERROR
	# PROGRAM ENTER HERE, MEANS THE
	# BACKPRESSURE MECHANISM IS BORKEN
	lhu x13, R16_UEP4_CTRLH(x14)
	andi x13, x13, ~(USBFS_UEP_R_RES_MASK)
	ori  x13, x13, USBFS_UEP_R_RES_STALL
	sh x13, R16_UEP4_CTRLH(x14)
	j USBFSD_PROC_TRANS_END

USBFSD_PROC_EP4_OUT:
	lbu x13, R8_USBFS_INT_ST(x14)
	andi x12, x13, USBFS_UIS_TOG_OK
	beqz x12, USBFSD_PROC_TRANS_END
	la x13, USBFSD_EP4_OUT_DMABUF
	lhu x12, R16_USBFS_RX_LEN(x14)
	la x31, USBFSD_COM0_RX_FIFO
	lhu x30, FIFO8_SIZE(x31)
	lhu x29, FIFO8_HEAD(x31)
	lhu x28, FIFO8_TAIL(x31)
	sub x7, x28, x29
	add x7, x7, x30
	remu x7, x7, x30
	sub x7, x30, x7
	addi x7, x7, -1
	bgt x12, x7, USBFSD_EP4_OUT_STALL
	beqz x12, 2f
1:
	add x7, x31, x28
	lbu x6, 0(x13)
	sb x6, 6(x7)
	fence rw, rw
	addi x28, x28, 1
	remu x28, x28, x30
	sh x28, FIFO8_TAIL(x31)
	addi x13, x13, 1
	addi x12, x12, -1
	bnez x12, 1b
2:
	sub x7, x28, x29
	add x7, x7, x30
	remu x7, x7, x30
	sub x7, x30, x7
	addi x7, x7, -1
	li x6, (USBFSD_COM0_RX_EP_SIZE * 2)
	bgt x7, x6, 1f # FLOW CONTROL
	lhu x13, R16_UEP4_CTRLH(x14)
	andi x13, x13, ~(USBFS_UEP_R_RES_MASK)
	ori x13, x13, (USBFS_UEP_R_RES_NAK)
	sh x13, R16_UEP4_CTRLH(x14)
1:
	lhu x13, R16_UEP4_CTRLH(x14)
	xori x13, x13, USBFS_UEP_R_TOG
	sh x13, R16_UEP4_CTRLH(x14)
	j USBFSD_PROC_TRANS_END

USBFSD_PROC_EP5_IN:
	lhu x13, R16_UEP5_CTRLH(x14)
	xori x13, x13, USBFS_UEP_T_TOG
	sh x13, R16_UEP5_CTRLH(x14)
	lhu x13, R16_UEP5_CTRLH(x14)
	andi x13, x13, ~(USBFS_UEP_T_RES_MASK)
	ori x13, x13, (USBFS_UEP_T_RES_NAK)
	sh x13, R16_UEP5_CTRLH(x14)
	j USBFSD_PROC_TRANS_END

USBFSD_PROC_TRANS:
	lbu x13, R8_USBFS_INT_ST(x14)
	andi x12, x13, USBFS_UIS_TOKEN_MASK
	xori x11, x12, USBFS_UIS_TOKEN_SOF
	beqz x11, USBFSD_PROC_SOF
	xori x11, x12, USBFS_UIS_TOKEN_SETUP
	beqz x11, USBFSD_PROC_SETUP
	andi x12, x13, (USBFS_UIS_TOKEN_MASK | USBFS_UIS_ENDP_MASK)
	xori x11, x12, (USBFS_UIS_TOKEN_IN | 0)
	beqz x11, USBFSD_PROC_EP0_IN
	xori x11, x12, (USBFS_UIS_TOKEN_IN | 4)
	beqz x11, USBFSD_PROC_EP4_IN
	xori x11, x12, (USBFS_UIS_TOKEN_IN | 5)
	beqz x11, USBFSD_PROC_EP5_IN
	xori x11, x12, (USBFS_UIS_TOKEN_OUT | 0)
	beqz x11, USBFSD_PROC_EP0_OUT
	xori x11, x12, (USBFS_UIS_TOKEN_OUT | 4)
	beqz x11, USBFSD_PROC_EP4_OUT
	j USBFSD_PROC_TRANS_END

USBFSD_PROC_BUS_RST:
	sb x0, R8_USBFS_DEV_ADDR(x14)
	la x13, USBFSD_DEV_ADDR
	sb x0, 0(x13)
	la x13, USBFSD_DEV_CFG
	sb x0, 0(x13)
	USBFSD_EP_INIT
	li x13, USBFS_UIF_BUS_RST
	sb x13, R8_USBFS_INT_FG(x14)
	mret

USBFSD_PROC_SUSPEND:
	li x13, USBFS_UIF_SUSPEND
	sb x13, R8_USBFS_INT_FG(x14)
	mret

	.P2ALIGN 2, 0
USBFSD_ISR:
	li x14, USBFS_BASE
	lbu x13, R8_USBFS_INT_FG(x14)
	andi x12, x13, USBFS_UIF_TRANSFER
	bnez x12, USBFSD_PROC_TRANS
	andi x12, x13, USBFS_UIF_BUS_RST
	bnez x12, USBFSD_PROC_BUS_RST
	andi x12, x13, USBFS_UIF_SUSPEND
	bnez x12, USBFSD_PROC_SUSPEND
	sb x13, R8_USBFS_INT_FG(x14)
	mret

	.POPSECTION .text

	DEFW USBFSD_INIT, "USBFSD-INIT"
	# ( -- )
	li x14, USBFS_BASE

	sb x0, R8_USBFS_BASE_CTRL(x14)
	sb x0, R8_UEP4_1_MOD(x14)
	sb x0, R8_UEP2_3_MOD(x14)
	sb x0, R8_UEP567_MOD(x14)
	sw x0, R32_UEPX_MOD(x14)

	la x13, USBFSD_EP0_DMABUF
	sw x13, R32_UEP0_DMA(x14)
	# EP0 EP4 SHARE A DMA ADDRESS REGISTER

	la x13, USBFSD_EP5_DMABUF
	sw x13, R32_UEP5_DMA(x14)

	li x13, (USBFS_UEP4_TX_EN | USBFS_UEP4_RX_EN)
	sb x13, R8_UEP4_1_MOD(x14)
	li x13, (USBFS_UEP5_TX_EN | USBFS_UEP5_RX_EN)
	sb x13, R8_UEP567_MOD(x14)

	USBFSD_EP_INIT

	sb x0, R8_USBFS_DEV_ADDR(x14)
	li x13, USBFS_UC_DEV_PU_EN | USBFS_UC_INT_BUSY | USBFS_UC_DMA_EN
	sb x13, R8_USBFS_BASE_CTRL(x14)

	li x13, 0xFF
	sb x13, R8_USBFS_INT_FG(x14)

	li x13, USBFS_UD_PD_DIS | USBFS_UD_PORT_EN
	sb x13, R8_USBFS_UDEV_CTRL(x14)

	li x13, USBFS_UIE_BUS_RST | USBFS_UIE_TRANSFER | USBFS_UIE_SUSPEND
	sb x13, R8_USBFS_INT_EN(x14)

	csrr x14, mtvec
	andi x14, x14, ~(0x3)
	la x13, USBFSD_ISR
	sw x13, (IRQN_USBFS * 4)(x14)
	fence iorw, iorw

	li x14, (PFIC_BASE + R32_PFIC_IENR1)
	li x13, (1 << (IRQN_USBFS % 32))
	sw x13, ((IRQN_USBFS / 32) * 4)(x14)

	ret
	ENDW USBFSD_INIT

	DEFW USBFSD_IS_CONNECTED, "USBFSD-CONNECTED?"
	# ( -- FLAG )
	PPUSH x15
	la x14, USBFSD_DEV_CFG
	lbu x13, 0(x14)
	li x15, -1
	bnez x13, 1f
	li x15, 0
1:
	ret
	ENDW USBFSD_IS_CONNECTED

	DEFW USBFSD_EP4_OUT_ISNAK, "USBFS-EP4-OUT-NAK?"
	# ( -- FLAG )
	PPUSH x15
	la x14, USBFS_BASE
	lhu x13, R16_UEP4_CTRLH(x14)
	andi x13, x13, (USBFS_UEP_R_RES_MASK)
	xori x13, x13, USBFS_UEP_R_RES_NAK
	li x15, -1
	beqz x13, 1f
	li x15, 0
1:
	ret
	ENDW USBFSD_EP4_OUT_ISNAK

	DEFW USBFSD_EP4_IN_ISNAK, "USBFS-EP4-IN-NAK?"
	# ( -- FLAG )
	PPUSH x15
	la x14, USBFS_BASE
	lhu x13, R16_UEP4_CTRLH(x14)
	andi x13, x13, (USBFS_UEP_T_RES_MASK)
	xori x13, x13, USBFS_UEP_T_RES_NAK
	li x15, -1
	beqz x13, 1f
	li x15, 0
1:
	ret
	ENDW USBFSD_EP4_IN_ISNAK

	DEFW USBFSD_PROC_COM0_RX, "USBFSD-PROC-COM0-RX"
	RPUSH x1
	FC USBFSD_IS_CONNECTED
	ZBR 1f
	FC USBFSD_COM0_RX_FIFO, FIFO8_NUM_FREE
	LIT (USBFSD_COM0_RX_EP_SIZE * 2)
	FC GT, USBFSD_EP4_OUT_ISNAK, AND
	ZBR 1f
	FC IRQN_USBFS, PFIC_IRQ_DIS
	li x14, USBFS_BASE
	lhu x13, R16_UEP4_CTRLH(x14)
	andi x13, x13, ~(USBFS_UEP_R_RES_MASK)
	ori x13, x13, (USBFS_UEP_R_RES_ACK)
	sh x13, R16_UEP4_CTRLH(x14)
	FC IRQN_USBFS, PFIC_IRQ_EN
1:
	RPOP x1
	ret
	ENDW USBFSD_PROC_COM0_RX

	DEFW USBFSD_PROC_COM0_TX, "USBFSD-PROC-COM0-TX"
	RPUSH x1
	FC USBFSD_IS_CONNECTED
	ZBR 2f
	FC USBFSD_COM0_TX_FIFO, FIFO8_IS_EMPTY, INVERT
	FC USBFSD_EP4_IN_ISNAK, AND
	ZBR 2f
	FC USBFSD_COM0_TX_FIFO, DUP, FIFO8_NUM_USED
	LIT (USBFSD_COM0_TX_EP_SIZE - 1) # AVOID ZLP
	FC MIN
	li x14, USBFS_BASE
	sh x15, R16_UEP4_TX_LEN(x14)
	FC USBFSD_EP4_IN_DMABUF
1:
	FC TOR, OVER, FIFO8_POP, FROMR, SWAP, OVER, CSTORE
	FC 0X1, PLUS, SWAP, 0X1, MINUS, SWAP, OVER, EQZ
	ZBR 1b
	FC 3DROP
	FC IRQN_USBFS, PFIC_IRQ_DIS
	li x14, USBFS_BASE
	lhu x13, R16_UEP4_CTRLH(x14)
	andi x13, x13, ~(USBFS_UEP_T_RES_MASK)
	ori x13, x13, USBFS_UEP_T_RES_ACK
	sh x13, R16_UEP4_CTRLH(x14)
	FC IRQN_USBFS, PFIC_IRQ_EN
2:
	RPOP x1
	ret
	ENDW USBFSD_PROC_COM0_TX

