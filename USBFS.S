	lbu x13, USB_SETUP_BREQUEST(x14)
	li x12, USB_SET_ADDRESS
	bne x13, x12,  1f
	TC USBFSD_PROC_EP0_IN_SET_ADDR
1:
	TC USBFSD_TRANS_END
	ENDW USBFSD_PROC_EP0_IN_STAND

	DEFW USBFSD_PROC_EP0_IN, "USBFSD-PROC-EP0-IN"
	li x14, USBFS_BASE
	la x13, USBFSD_SETUP_COPY
	lhu x12, USB_SETUP_WLENGTH(x13)
	bnez x12, 1f
	lhu x12, R16_UEP0_CTRLH(x14)
	andi x12, x12, ~(USBFS_UEP_R_RES_MASK)
	ori x12, x12, USBFS_UEP_R_TOG | USBFS_UEP_R_RES_ACK
	sh x12, R16_UEP0_CTRLH(x14)
1:
	lbu x12, USB_SETUP_BMREQTYPE(x13)
	andi x11, x12, USB_SETUP_REQTYPE_MASK
	li x10, USB_SETUP_REQTYPE_STAND
	bne x11, x10, 1f
	TC USBFSD_PROC_EP0_IN_STAND
1:

	TC USBFSD_TRANS_END
	ENDW USBFSD_PROC_EP0_IN

	DEFW USBFSD_PROC_EP0_OUT, "USBFSD-PROC-EP0-OUT"
	li x14, USBFS_BASE
	lbu x13, R8_USBFS_INT_ST(x14)
	andi x12, x13, USBFS_UIS_TOG_OK
	bnez x12, 1f
	TC USBFSD_TRANS_END
1:
	TC USBFSD_TRANS_END
	ENDW USBFSD_PROC_EP0_OUT

	DEFW USBFSD_EP4_IN_IS_NAK, "USBFSD-EP4-IN-NAK?"
	# ( -- FLAG )
	PPUSH x15
	li x14, USBFS_BASE
	lhu x13, R16_UEP4_CTRLH(x14)
	andi x13, x13, USBFS_UEP_T_RES_MASK
	xori x13, x13, USBFS_UEP_T_RES_NAK
	li x15, -1
	beqz x13, 1f
	li x15, 0
1:
	ret
	ENDW USBFSD_EP4_IN_IS_NAK

	DEFW USBFSD_PROC_EP4_IN, "USBFSD-PROC-EP4-IN"
	li x14, USBFS_BASE
	lhu x13, R16_UEP4_CTRLH(x14)
	andi x13, x13, ~(USBFS_UEP_T_RES_MASK)
	ori x13, x13, USBFS_UEP_T_RES_NAK
	sh x13, R16_UEP4_CTRLH(x14)
	lhu x13, R16_UEP4_CTRLH(x14)
	xori x13, x13, USBFS_UEP_T_TOG
	sh x13, R16_UEP4_CTRLH(x14)
	TC USBFSD_TRANS_END
	ENDW USBFSD_PROC_EP4_IN

	DEFW USBFSD_EP4_OUT_IS_NAK, "USBFSD-EP4-OUT-NAK?"
	# ( -- FLAG )
	PPUSH x15
	li x14, USBFS_BASE
	lhu x13, R16_UEP4_CTRLH(x14)
	andi x13, x13, USBFS_UEP_R_RES_MASK
	xori x13, x13, USBFS_UEP_R_RES_NAK
	li x15, -1
	beqz x13, 1f
	li x15, 0
1:
	ret
	ENDW USBFSD_EP4_OUT_IS_NAK

	DEFW USBFSD_PROC_EP4_OUT, "USBFSD-PROC-EP4-OUT"
	li x14, USBFS_BASE
	lbu x13, R8_USBFS_INT_ST(x14)
	andi x12, x13, USBFS_UIS_TOG_OK
	bnez x12, 1f
	TC USBFSD_TRANS_END
1:
	lhu x10, R16_USBFS_RX_LEN(x14)
	lhu x13, R16_UEP4_CTRLH(x14)
	xori x13, x13, USBFS_UEP_R_TOG;
	sh x13, R16_UEP4_CTRLH(x14)
	mv x13, x10
	beqz x13, 1f
	la x14, USBFSD_EP4_OUT_DMABUF
	lbu x13, 0(x14)
	li x12, 63
	remu x13, x13, x12
	addi x14, x14, 1
	beqz x13, 1f
	addi x9, x9, -8
	sw x14, 0(x9)
	sw x15, 4(x9)
	mv x15, x13
	# ( BUFFER COUNT )
	RPUSH x1
	FC USBFSD_HID0_OUT_FIFO, FIFO8_NUM_FREE
	FC OVER, LT, INVERT
	ZBR 2f
3:
	FC OVER, CLOAD, USBFSD_HID0_OUT_FIFO, FIFO8_PUSH
	addi x15, x15, -1
	FC SWAP
	addi x15, x15, 1
	FC SWAP
	FC DUP, EQZ
	ZBR 3b
2:
	FC 2DROP, USBFSD_HID0_OUT_FIFO, FIFO8_NUM_FREE
	LIT (16 * 2)
	FC GT, INVERT
	ZBR 3f
	li x14, USBFS_BASE
	lhu x13, R16_UEP4_CTRLH(x14)
	andi x13, x13, ~(USBFS_UEP_R_RES_MASK)
	ori x13, x13, USBFS_UEP_R_RES_NAK
	sh x13, R16_UEP4_CTRLH(x14)
3:
	RPOP x1
1:
	TC USBFSD_TRANS_END
	ENDW USBFSD_PROC_EP4_OUT

	DEFW USBFSD_PROC_TRANSFER, "USBFSD-PROC-TRANSFER"
	# ( -- )
	li x14, USBFS_BASE
	lbu x13, R8_USBFS_INT_ST(x14)
	andi x12, x13, USBFS_UIS_TOKEN_MASK
	li x11, USBFS_UIS_TOKEN_SETUP
	bne x12, x11, 1f
	TC USBFSD_PROC_SETUP
1:
	andi x12, x13, (USBFS_UIS_TOKEN_MASK | USBFS_UIS_ENDP_MASK)
	li x11, (USBFS_UIS_TOKEN_IN | 0X00)
	bne x12, x11, 1f
	TC USBFSD_PROC_EP0_IN
1:
	li x11, (USBFS_UIS_TOKEN_OUT | 0X00)
	bne x12, x11, 1f
	TC USBFSD_PROC_EP0_OUT
1:
	li x11, (USBFS_UIS_TOKEN_IN | 0X04)
	bne x12, x11, 1f
	TC USBFSD_PROC_EP4_IN
1:
	li x11, (USBFS_UIS_TOKEN_OUT | 0X04)
	bne x12, x11, 1f
	TC USBFSD_PROC_EP4_OUT
1:

	TC USBFSD_TRANS_END
	ENDW USBFSD_PROC_TRANSFER

