	DEFW USBFSD_PROC_EP0_IN_SET_ADDR, "USBFSD-PROC-EP0-IN-SET-ADDR"
	li x14, USBFS_BASE
	la x13, USBFSD_DEV_ADDR
	lbu x12, 0(x13)
	sb x12, R8_USBFS_DEV_ADDR(x14)
	TC USBFSD_TRANS_END
	ENDW USBFSD_PROC_EP0_IN_SET_ADDR

	DEFW USBFSD_PROC_EP0_IN_STAND, "USBFSD-PROC-EP0-IN-STAND"
