	DEFW USBFS_CLK_INIT, "USBFS-CLK-INIT"
	# ( -- )
	la x14, RCC_BASE
	lw x13, R32_RCC_AHBRSTR(x14)
	li x12, ~(RCC_USBFSRST)
	and x13, x13, x12
	sw x13, R32_RCC_AHBRSTR(x14)
	lw x13, R32_RCC_AHBPCENR(x14)
	li x12, RCC_USBFSEN
	or x13, x13, x12
	sw x13, R32_RCC_AHBPCENR(x14)
	ret
	ENDW USBFS_CLK_INIT

	# !!!!!!!!!!! DISABLE USBPHY LDO IS DANGROUS WHEN VDD IS 5V !!!!!!!!!!!
	DEFW USBPHY_LDO_DIS, "USBPHY-LDO-DIS"
	# ( -- )
	li x14, AFIO_BASE
	lw x13, R32_AFIO_CTLR(x14)
	or x13, x13, AFIO_USBPHY_LDODIS
	sw x13, R32_AFIO_CTLR(x14)
	ret
	ENDW USBPHY_LDO_DIS

	DEFW USBPHY_LDO_EN, "USBPHY-LDO-EN"
	# ( -- )
	li x14, AFIO_BASE
	lw x13, R32_AFIO_CTLR(x14)
	andi x13, x13, ~(AFIO_USBPHY_LDODIS)
	sw x13, R32_AFIO_CTLR(x14)
	ret
	ENDW USBPHY_LDO_EN
