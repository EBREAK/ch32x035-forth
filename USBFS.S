	DEFW USBFS_CLK_INIT, "USBFS-CLK-INIT"
	# ( -- )
	la x14, RCC_BASE
	lw x13, R32_RCC_AHBRSTR(x14)
	li x12, ~(RCC_USBFSRST)
	and x13, x13, x12
	sw x13, R32_RCC_AHBRSTR(x14)
	lw x13, R32_RCC_AHBPCENR(x14)
	li x12, RCC_USBFSEN
	or x13, x13, x12
	sw x13, R32_RCC_AHBPCENR(x14)
	ret
	ENDW USBFS_CLK_INIT

	DEFW USBFSH_GPIO_INIT, "USBFSH-GPIO-INIT"
	# ( -- )
	RPUSH x1
	FC VDD_IS5V
	li x14, AFIO_BASE
	lw x13, R32_AFIO_CTLR(x14)
	li x12, ~(AFIO_USBPHY_LDODIS | AFIO_USB_DP_PUE_MASK | AFIO_USB_DM_PUE_MASK)
	and x13, x13, x12
	xori x12, x15, -1
	andi x12, x12, 0x1
	PPOP x15
	slli x12, x12, 6 # AFIO_USBPHY_LDODIS/EN
	or x13, x13, x12
	li x12, AFIO_USBPHY_IOEN
	or x13, x13, x12
	sw x13, R32_AFIO_CTLR(x14)

	li x14, GPIOC_BASE
	lw x13, R32_GPIO_CFGXR(x14)
	andi x13, x13, ~(0xFF)
	ori x13, x13, 0x44
	sw x13, R32_GPIO_CFGXR(x14)
	lw x13, R32_GPIO_OUTDR(x14)
	li x12, ~(0x3 << 16)
	and x13, x13, x12
	sw x13, R32_GPIO_OUTDR(x14)
	lw x13, R32_GPIO_CFGXR(x14)
	andi x13, x13, ~(0xFF)
	ori x13, x13, 0x88
	sw x13, R32_GPIO_CFGXR(x14)
	RPOP x1
	ret
	ENDW USBFSH_GPIO_INIT


	DEFW USBFSH_INIT, "USBFSH-INIT"
	# ( -- )
	li x14, USBFS_BASE
	li x13, USBFS_UC_MODE_HOST
	sb x13, R8_USBFS_BASE_CTRL(x14)
1:
	# TODO: MY BOARD USE CH32X035F8U6 NOT SUPPORT USB HOST
	# I NEED BUY CHIP CH32X035G8U6/G8R6/C8T6/R8T6 TO TEST IT
	# CH32X035F8U6/F7P6/D8U6, CH32X033F8P6 WILL LOOP FOREVER
	lbu x13, R8_USBFS_BASE_CTRL(x14)
	andi x13, x13, USBFS_UC_MODE_HOST
	beqz x13, 1b

	sb x0, R8_USBFS_HOST_CTRL(x14)
	sb x0, R8_USBFS_DEV_ADDR(x14)
	sb x0, R8_UHOST_EP_MOD(x14)
	sb x0, R8_UHOST_RX_CTRL(x14)
	sb x0, R8_UHOST_TX_CTRL(x14)

	la x13, FORTH_DP
	lw x12, 0(x13)
	addi x12, x12, 3
	andi x12, x12, -4
	sh x12, R16_UHOST_RX_DMA(x14)
	addi x12, x12, 64
	sh x12, R16_UHOST_TX_DMA(x14)
	addi x12, x12, 64
	sw x12, 0(x13)

	li x13, (USBFS_UH_EP_TX_EN | USBFS_UH_EP_RX_EN)
	sb x13, R8_UHOST_EP_MOD(x14)

	lbu x13, R8_USBFS_BASE_CTRL(x14)
	ori x13, x13, (USBFS_UC_INT_BUSY | USBFS_UC_DMA_EN)
	sb x13, R8_USBFS_BASE_CTRL(x14)

	li x13, USBFS_UH_SOF_EN
	sb x13, R8_UHOST_SETUP(x14)

	li x13, 0xFF
	sb x13, R8_USBFS_INT_FG(x14)
	li x13, USBFS_UIE_DETECT | USBFS_UIE_TRANSFER
	sb x13, R8_USBFS_INT_EN(x14)

	ret
	ENDW USBFSH_INIT

