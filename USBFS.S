	DEFW USBFSD_HID0_TX_PROC, "USBFSD-HID0-TX-PROC"
	# ( -- )
	RPUSH x1
	FC USBFSD_HID0_IN_FIFO, FIFO8_IS_EMPTY, INVERT
	ZBR 1f
	FC USBFSD_EP4_IN_IS_NAK
	ZBR 1f
	FC USBFSD_HID0_IN_FIFO, FIFO8_NUM_USED, 0XE, MIN
	LAT USBFSD_EP4_IN_DMABUF
	FC 2DUP, CSTORE
	addi x15, x15, 1
2:
	FC USBFSD_HID0_IN_FIFO, FIFO8_POP
	FC OVER, CSTORE
	addi x15, x15, 1
	FC SWAP
	addi x15, x15, -1
	FC SWAP, OVER, EQZ
	ZBR 2b
	FC 2DROP
	li x14, USBFS_BASE
	li x13, 16
	sh x13, R16_UEP4_TX_LEN(x14)
	lhu x13, R16_UEP4_CTRLH(x14)
	andi x13, x13, ~(USBFS_UEP_T_RES_MASK)
	ori x13, x13, USBFS_UEP_T_RES_ACK
	sh x13, R16_UEP4_CTRLH(x14)
1:
	RPOP x1
	ret
	ENDW USBFSD_HID0_TX_PROC

