	USBFSD_EP_INIT

	sb x0, R8_USBFS_DEV_ADDR(x14)
	li x13, USBFS_UC_DEV_PU_EN | USBFS_UC_INT_BUSY | USBFS_UC_DMA_EN
	sb x13, R8_USBFS_BASE_CTRL(x14)

