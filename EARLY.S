	.PUSHSECTION .text.early
EARLY_INIT:
	li x10, FLASH_BASE

	# IMPORTANT
SET_FLASH_LATENCY:
	lw x11, R32_FLASH_ACTLR(x10)
	andi x11, x11, ~(FLASH_LATENCY_MASK)
	sw x11, R32_FLASH_ACTLR(x10)
	nop
	nop
	nop
	nop
	or x11, x11, FLASH_LATENCY_2
	sw x11, R32_FLASH_ACTLR(x10)
	nop
	nop
	nop
	nop

	li x10, RCC_BASE
WAIT_HSIRDY:
	lw x11, R32_RCC_CTLR(x10)
	andi x11, x11, RCC_HSIRDY
	beqz x11, WAIT_HSIRDY
	# HSI 48Mhz

SET_HPRE:
	lw x11, R32_RCC_CFGR0(x10)
	andi x11, x11, ~(RCC_HPRE_MASK)
	ori x11, x11, RCC_HPRE_1DIV
	sw x11, R32_RCC_CFGR0(x10)
	# HCLK 48Mhz

DEASSERT_GPIOA_RST:
	lw x11, R32_RCC_APB2PRSTR(x10)
	andi x11, x11, ~(RCC_IOPARST)
	sw x11, R32_RCC_APB2PRSTR(x10)

GPIOA_CLK_ON:
	lw x11, R32_RCC_APB2PCENR(x10)
	ori x11, x11, RCC_IOPAEN
	sw x11, R32_RCC_APB2PCENR(x10)

DEASSERT_GPIOB_RST:
	lw x11, R32_RCC_APB2PRSTR(x10)
	andi x11, x11, ~(RCC_IOPBRST)
	sw x11, R32_RCC_APB2PRSTR(x10)

GPIOB_CLK_ON:
	lw x11, R32_RCC_APB2PCENR(x10)
	ori x11, x11, RCC_IOPBEN
	sw x11, R32_RCC_APB2PCENR(x10)

DEASSERT_USART2_RST:
	lw x11, R32_RCC_APB1PRSTR(x10)
	li x12, ~(RCC_USART2RST)
	and x11, x11, x12
	sw x11, R32_RCC_APB1PRSTR(x10)


USART2_CLK_ON:
	lw x11, R32_RCC_APB1PCENR(x10)
	li x12, RCC_USART2EN
	or x11, x11, x12
	sw x11, R32_RCC_APB1PCENR(x10)

	li x10, GPIOB_BASE
LED_PIN_MODE:
	lw x11, R32_GPIO_CFGHR(x10)
	li x12, ~(GPIO_MODE_MASK << 16)
	and x11, x11, x12
	li x12, (GPIO_MODE_PPOUT << 16)
	or x11, x11, x12
	sw x11, R32_GPIO_CFGHR(x10)

LED_PIN_HIGH:
	li x11, (1 << 12)
	sw x11, R32_GPIO_BSHR(x10)

	li x10, GPIOA_BASE

USART2_PIN_MODE:
	lw x11, R32_GPIO_CFGLR(x10)
	li x12, ~(GPIO_MODE_MASK << 8) # PA2 TX
	and x11, x11, x12
	li x12, (GPIO_MODE_MUPPOUT << 8)
	or x11, x11, x12
	li x12, ~(GPIO_MODE_MASK << 12) # PA3 RX
	and x11, x11, x12
	li x12, (GPIO_MODE_FLOATIN << 12)
	or x11, x11, x12
	sw x11, R32_GPIO_CFGLR(x10)

USART2_INIT:
	li x10, USART2_BASE
	sw x0, R32_USART_CTLR1(x10)
	sw x0, R32_USART_CTLR2(x10)
	sw x0, R32_USART_CTLR3(x10)
	# USART CLOCK SOURCE IS APB1
	# APB1 CLOCK SOURCE IS HCLK
	# HCLK CLOCK SOURCE IS SYSCLK
	# SYSCLK CLOCK SOURCE IS HSI 48Mhz / 1 = 48Mhz
	# (48 * 1000 * 1000) / (26.0625 * 16) =  115107.91366906474
	# 1 / 16 = 0.625
	# M = 26
	# F = 1
	.SET USART_BAUD_115200, ((26 << 4) | (1 << 0))
	li x12, USART_BAUD_115200
	sw x12, R32_USART_BRR(x10)
	li x11, USART_UE | USART_TE | USART_RE
	sw x11, R32_USART_CTLR1(x10)

	ret
	.POPSECTION
