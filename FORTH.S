	# PSP: x9
	# UP:  x4

	# TAIL TEMP REGISTER: x31 (ONLY USE FOR GENERATE LONG JMP)

	.MACRO DEFUSER LABEL, NEXT, RAS, SAV
		.PUSHSECTION .data
		.P2ALIGN 2, 0
	PSTK_\LABEL:
		.FILL STACK_DEPTH, 4, 0xBAADBEEF
	PSTK_TOP_\LABEL:
	RSTK_\LABEL:
		.FILL STACK_DEPTH, 4, 0xBADB0744
	RSTK_TOP_\LABEL:
		.P2ALIGN 2, 0
	USER_\LABEL:
		.4BYTE USER_END_\LABEL - USER_\LABEL
		.4BYTE \RAS
		.4BYTE \SAV
		.4BYTE TOS_INIT
		.4BYTE PSTK_TOP_\LABEL
		.4BYTE PSTK_TOP_\LABEL
		.4BYTE RSTK_TOP_\LABEL
		.4BYTE RSTK_TOP_\LABEL
		.4BYTE USER_\NEXT
		.4BYTE W_EARLY_EMIT
		.4BYTE W_EARLY_KEYAVA
		.4BYTE W_EARLY_KEY
		.4BYTE W_HEXDOT
		.4BYTE WIB_\LABEL
		.4BYTE 0
		.4BYTE 0
	USER_END_\LABEL:
		# RESV SPACE FOR GROW
		.FILL 8, 4, 0
		.POPSECTION
	.ENDM

