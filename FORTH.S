CODE_BACK:
	FC PAUSE, IWDG_FEED
	FC USBFSD_PROC_COM0_RX, USBFSD_PROC_COM0_TX
	j CODE_BACK

CODE_ROOT:
	//FC SELFTEST

	FC SYSTICK_INIT
	FC IWDG_INIT, IWDG_FEED
	FC USBFS_CLK_INIT, USBFSD_GPIO_INIT, USBFSD_INIT
	LAT W_USBFSD_COM0_EMIT
	FC UPLOAD, USER_EMIT, PLUS, STORE
	LAT W_USBFSD_COM0_KEYAVA
	FC UPLOAD, USER_KEYAVA, PLUS, STORE
	LAT W_USBFSD_COM0_KEY
	FC UPLOAD, USER_KEY, PLUS, STORE

	.PUSHSECTION .rodata
STR_CH32X03:
	.ASCII "CH32X03"
	.POPSECTION
	LAT STR_CH32X03
	LIT 7
	FC CR, TYPE, CHIP_VARIANT, TYPE, CR

	.PUSHSECTION .rodata.motd
MOTD:
	.ASCII "+-+-+-+-+-+\r\n"
	.ASCII "|F|O|R|T|H|\r\n"
	.ASCII "+-+-+-+-+-+"
	.SET LEN_MOTD, . - MOTD
	.POPSECTION
	LAT MOTD
	LIT LEN_MOTD
	FC TYPE, CR

	auipc x14, 0
	sw x14, USER_SAV(x4)
	TC REPL

	li x10, USART2_BASE
1:
	lw x11, R32_USART_STATR(x10)
	andi x11, x11, USART_TC
	beqz x11, 1b
	li x11, 'F'
	sw x11, R32_USART_DATAR(x10)
1:
	j 1b

forth:
	# INIT EMPTY FORTH DICT IN SRAM
	la x10, _forth_dict_end
	sb zero, -1(x10)
	sb zero, -2(x10)

	# INIT FORTH CONTEXT
	la x10, CONTEXT
	la x11, _forth_dict_end - 2 # DICT IN RAM
	sw x11, 0(x10)
	la x11, _forth_dict_rom_start # DICT IN ROM
	sw x11, 4(x10)

	# clean register
	li x1, 0
	# dont clear sp gp
	li x4, 0
	li x5, 0
	li x6, 0
	li x7, 0
	li x8, 0
	li x9, 0
	li x10, 0
	li x11, 0
	li x12, 0
	li x13, 0
	li x14, 0
	li x15, 0

	la x4, USER_ROOT
	lw x15, USER_TOS(x4)
	lw x8, USER_RSP(x4)
	lw x9, USER_PSP(x4)
	lw x1, USER_SAV(x4)
	ret
	.POPSECTION
